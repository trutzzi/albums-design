/**
 * Where focus goes in a list of `count` items when `key` is pressed on item `current`:
 * the arrows step and wrap round, Home and End jump to the ends. `null` for any other key,
 * so the caller leaves the key alone.
 */
export function nextFocusIndex(key: string, current: number, count: number): number | null {
  if (count === 0) return null;
  switch (key) {
    case "ArrowDown":
      return current < 0 ? 0 : (current + 1) % count;
    case "ArrowUp":
      return current < 0 ? count - 1 : (current - 1 + count) % count;
    case "Home":
      return 0;
    case "End":
      return count - 1;
    default:
      return null;
  }
}

/** Elements a keyboard user can reach with Tab inside a container. */
export const FOCUSABLE =
  'a[href], button:not([disabled]), input:not([disabled]), select:not([disabled]), textarea:not([disabled]), [tabindex]:not([tabindex="-1"])';
